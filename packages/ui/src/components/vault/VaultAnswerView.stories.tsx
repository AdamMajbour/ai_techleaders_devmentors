import type { Meta, StoryObj } from '@storybook/react-vite';
import { expect, within } from 'storybook/test';
import { VAULT_ANSWER, VAULT_CITATIONS, VAULT_QUESTION } from '../../../.storybook/blocks/sampleData';
import { VaultAnswerView } from './VaultAnswerView';

const meta = {
  title: 'Product/Vault/VaultAnswerView',
  component: VaultAnswerView,
  args: { question: VAULT_QUESTION, status: 'released', answerText: VAULT_ANSWER, citations: VAULT_CITATIONS },
  render: (args) => (
    <div className="max-w-session">
      <VaultAnswerView {...args} />
    </div>
  ),
} satisfies Meta<typeof VaultAnswerView>;

export default meta;
type Story = StoryObj<typeof meta>;

export const Released: Story = {
  play: async ({ canvasElement }) => {
    const canvas = within(canvasElement);
    await expect(canvas.getByText('Generated by AI from the notes below. Not written by the mentor.')).toBeVisible();
    await expect(canvas.getByRole('region', { name: 'Notes used' })).toBeVisible();
  },
};

export const Generating: Story = { args: { status: 'generating', answerText: undefined, citations: [] } };

export const WaitingForTheMentors: Story = { args: { status: 'pending_preview', answerText: undefined, citations: [], previewMinutes: 120 } };

export const Rejected: Story = { args: { status: 'rejected', answerText: undefined, citations: [], refund: 'pending_approval' } };

export const Expired: Story = { args: { status: 'expired', answerText: undefined, citations: [], refund: 'processing' } };

export const NotesDidNotCoverTheQuestion: Story = {
  args: { status: 'generation_failed', failureReason: 'unanswerable', answerText: undefined, citations: [], refund: 'refunded' },
};

export const WritingFailed: Story = {
  args: { status: 'generation_failed', failureReason: 'unavailable', answerText: undefined, citations: [], refund: 'pending_approval' },
};

export const CancelledByTheOperator: Story = { args: { status: 'cancelled', answerText: undefined, citations: [], refund: 'processing' } };

export const LinkInGeneratedTextIsPlain: Story = {
  args: { answerText: 'Open [the vendor docs](https://example.com/docs) for the exact flags.' },
  play: async ({ canvasElement }) => {
    const canvas = within(canvasElement);
    await expect(canvas.queryByRole('link')).toBeNull();
    await expect(canvas.getByText(/the vendor docs/)).toBeVisible();
  },
};

