import { render, screen, within } from '@testing-library/react';
import { VaultAnswerView, type VaultAnswerStatus } from './VaultAnswerView';

const base = { question: 'How do I debug a restart loop after an ingress upgrade?' };
const citations = [
  { noteId: 'n1', mentorName: 'Ada Kowalska', noteTitle: 'Ingress upgrades on bare metal' },
  { noteId: 'n2', mentorName: 'Jan Nowak', noteTitle: 'Reading webhook logs' },
];

describe('VaultAnswerView', () => {
  it('always shows the seeker’s own question', () => {
    render(<VaultAnswerView {...base} status="generating" />);
    expect(screen.getByText(base.question)).toBeVisible();
  });

  it('says it is writing, with a way to leave', () => {
    render(<VaultAnswerView {...base} status="generating" />);
    expect(screen.getByRole('status')).toHaveTextContent('Writing your answer…');
    expect(screen.getByText(/You can leave this page/)).toBeVisible();
  });

  it('says the mentors read the answer first, with the time when known', () => {
    const { rerender } = render(<VaultAnswerView {...base} status="pending_preview" previewMinutes={120} />);
    expect(screen.getByText(/up to 120 minutes\. You are refunded if they do not approve\./)).toBeVisible();
    rerender(<VaultAnswerView {...base} status="pending_preview" />);
    expect(screen.queryByText(/up to/)).not.toBeInTheDocument();
  });

  it('labels a released answer as AI-generated, permanently, before the text', () => {
    render(<VaultAnswerView {...base} status="released" answerText="Read the previous logs." citations={citations} />);
    const label = screen.getByText('Generated by AI from the notes below. Not written by the mentor.');
    const text = screen.getByText('Read the previous logs.');
    expect(label.compareDocumentPosition(text) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy();
  });

  it('lists each cited note as "Mentor name, note title" and shows no rating', () => {
    const { container } = render(<VaultAnswerView {...base} status="released" answerText="x" citations={citations} />);
    const items = within(screen.getByRole('region', { name: 'Notes used' })).getAllByRole('listitem');
    expect(items.map((item) => item.textContent)).toEqual(['Ada Kowalska, Ingress upgrades on bare metal', 'Jan Nowak, Reading webhook logs']);
    expect(container.textContent).not.toMatch(/★|rating|stars|score/i);
  });

  it('shows a link inside generated text as plain text, not as a link', () => {
    render(<VaultAnswerView {...base} status="released" answerText="Open [the docs](https://evil.example) now." citations={citations} />);
    expect(screen.queryByRole('link')).not.toBeInTheDocument();
    expect(screen.getByText(/the docs/)).toBeVisible();
  });

  it.each<[VaultAnswerStatus, RegExp]>([
    ['rejected', /did not approve this answer\. You are refunded\./],
    ['expired', /did not answer in time\. You are refunded\./],
    ['cancelled', /was cancelled\. You are refunded\./],
  ])('says in words what happened for %s', (status, text) => {
    render(<VaultAnswerView {...base} status={status} />);
    expect(screen.getByText(text)).toBeVisible();
  });

  it('says the notes did not cover the question, and that nothing was kept', () => {
    render(<VaultAnswerView {...base} status="generation_failed" failureReason="unanswerable" />);
    expect(screen.getByText(/do not cover your question.*Nothing was kept/)).toBeVisible();
  });

  it('uses plain words for any other failure', () => {
    render(<VaultAnswerView {...base} status="generation_failed" failureReason="unavailable" />);
    expect(screen.getByText('We could not write the answer. You are refunded.')).toBeVisible();
  });

  it('says where the money stands in every ended state, except a released answer', () => {
    const { rerender } = render(<VaultAnswerView {...base} status="rejected" refund="pending_approval" />);
    expect(screen.getByText('Refund pending approval')).toBeVisible();
    rerender(<VaultAnswerView {...base} status="released" answerText="x" citations={citations} refund="refunded" />);
    expect(screen.queryByText('Refunded')).not.toBeInTheDocument();
  });

  it('announces changes politely', () => {
    const { container } = render(<VaultAnswerView {...base} status="generating" />);
    expect(container.querySelector('[aria-live="polite"]')).toBeInTheDocument();
  });
});
