import { MarkdownView } from '../../backend/content/MarkdownView';
import { LoadingMessage } from '../../backend/feedback/LoadingMessage';
import { RefundStatusLine, type RefundState } from '../bookings/BookingStatus';

export type VaultAnswerStatus = 'generating' | 'pending_preview' | 'released' | 'rejected' | 'expired' | 'generation_failed' | 'cancelled';
export type VaultFailureReason = 'unanswerable' | 'refused' | 'invalid_output' | 'unavailable' | 'config';

export interface VaultCitation {
  noteId: string;
  mentorName: string;
  noteTitle: string;
}

export interface VaultAnswerViewProps {
  question: string;
  status: VaultAnswerStatus;
  /** Present when `status` is `released`. Generated text: links in it are shown as plain text. */
  answerText?: string;
  /** The notes the answer was built from, as they were when it was written. */
  citations?: VaultCitation[];
  /** Set with `generation_failed`. `unanswerable` gets its own words. */
  failureReason?: VaultFailureReason;
  refund?: RefundState;
  /** How long the mentors have to read the answer. Written in the waiting message when known. */
  previewMinutes?: number;
}

// What the seeker sees of a vault answer, in every state. A released answer always carries the permanent label
// that it was generated by AI from the notes listed under it (D10, D14), and no rating (N02). Every other state
// says what happened and where the money stands.
export function VaultAnswerView({ question, status, answerText, citations = [], failureReason, refund = 'none', previewMinutes }: VaultAnswerViewProps) {
  return (
    <article aria-label="Vault answer" className="flex flex-col gap-between-groups">
      <section aria-label="Your question" className="flex flex-col gap-group">
        <h2 className="m-0 text-label font-strong text-headline">Your question</h2>
        <p className="m-0 whitespace-pre-line break-words text-body text-foreground">{question}</p>
      </section>
      <div aria-live="polite" className="flex flex-col gap-between-groups">
        {status === 'generating' ? (
          <div className="flex flex-col gap-group">
            <LoadingMessage message="Writing your answer…" />
            <p className="m-0 text-body text-foreground">You can leave this page. The answer will be here when it is ready.</p>
          </div>
        ) : null}
        {status === 'pending_preview' ? (
          <p className="m-0 text-body text-foreground">
            Waiting for the mentors whose notes were used. They read the answer first
            {previewMinutes ? `, up to ${previewMinutes} minutes` : ''}. You are refunded if they do not approve.
          </p>
        ) : null}
        {status === 'released' ? (
          <>
            <p className="m-0 text-label font-strong text-headline">Generated by AI from the notes below. Not written by the mentor.</p>
            {answerText ? <MarkdownView source={answerText} linkPolicy="none" /> : null}
            <section aria-label="Notes used" className="flex flex-col gap-group">
              <h2 className="m-0 text-label font-strong text-headline">Notes used</h2>
              <ul className="m-0 flex list-none flex-col gap-group p-0 text-body text-foreground">
                {citations.map((citation) => (
                  <li key={citation.noteId}>
                    {citation.mentorName}, {citation.noteTitle}
                  </li>
                ))}
              </ul>
            </section>
          </>
        ) : null}
        {status === 'rejected' ? (
          <p className="m-0 text-body text-foreground">The mentors whose notes were used did not approve this answer. You are refunded.</p>
        ) : null}
        {status === 'expired' ? <p className="m-0 text-body text-foreground">The mentors did not answer in time. You are refunded.</p> : null}
        {status === 'generation_failed' ? (
          <p className="m-0 text-body text-foreground">
            {failureReason === 'unanswerable'
              ? 'The notes do not cover your question, so no answer was written. Nothing was kept. You are refunded.'
              : 'We could not write the answer. You are refunded.'}
          </p>
        ) : null}
        {status === 'cancelled' ? <p className="m-0 text-body text-foreground">This answer was cancelled. You are refunded.</p> : null}
        {status !== 'generating' && status !== 'pending_preview' && status !== 'released' ? <RefundStatusLine refund={refund} /> : null}
      </div>
    </article>
  );
}
